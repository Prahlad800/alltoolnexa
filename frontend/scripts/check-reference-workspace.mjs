import {chromium,expect as baseExpect} from '@playwright/test';
const expect=baseExpect.configure({timeout:60000});
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1600,height:1100}});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
try{
 await page.goto('http://127.0.0.1:3000/tools/word-counter',{waitUntil:'domcontentloaded',timeout:120000});
 await expect(page.locator('html')).toHaveAttribute('data-theme','light');
 await expect(page.getByRole('navigation',{name:'Toolbox categories'})).toBeVisible();
 await expect(page.getByRole('list',{name:'Tool workflow'})).toBeVisible();
 await page.getByRole('searchbox',{name:'Search toolbox'}).fill('word counter');
 await expect(page.getByRole('navigation',{name:'Tool search results'})).toBeVisible();
 await page.getByRole('searchbox',{name:'Search toolbox'}).fill('');
 await page.waitForTimeout(700);
 const text=page.locator('.tool-form textarea').first();
 await text.fill('One two three');
 await page.locator('.tool-form button.primary').click();
 await expect(page.locator('.result-actions')).toBeVisible({timeout:60000});
 await page.screenshot({path:'logs/reference-word-light.png',timeout:60000});
 await page.getByRole('button',{name:'Use dark theme',exact:true}).click();
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
 const background=await page.evaluate(()=>getComputedStyle(document.body).backgroundColor);
 if(background!=='rgb(0, 0, 0)')throw Error('Dark background is not black: '+background);
 await page.screenshot({path:'logs/reference-word-dark.png',timeout:60000});
 await page.getByRole('searchbox',{name:'Search toolbox'}).fill('pdf merge');
 await expect(page.getByRole('navigation',{name:'Tool search results'}).getByRole('link',{name:'PDF Merge',exact:true})).toBeVisible();
 page.on('dialog',d=>d.accept());
 await page.goto('http://127.0.0.1:3000/tools/image-compressor',{waitUntil:'domcontentloaded',timeout:120000});
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
 await expect(page.locator('input[type=file]')).toBeVisible();
 await page.setViewportSize({width:390,height:844});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile workspace overflow');
 await page.screenshot({path:'logs/reference-mobile-dark.png',timeout:60000});
 await page.goto('http://127.0.0.1:3000/',{waitUntil:'domcontentloaded',timeout:120000});
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
 const home=await page.locator('main>div').evaluate(el=>getComputedStyle(el).backgroundColor);
 if(home!=='rgb(0, 0, 0)')throw Error('Homepage dark background is not black: '+home);
 console.log(JSON.stringify({wordCounter:'working',toolboxSearch:'working',darkMode:'black',themeRestored:true,mobileOverflow:false,homepageDark:'black',browserErrors:errors}));
 if(errors.length)throw Error('Browser errors');
}finally{await browser.close();}
